def expand(query: str, mode: str) -> list[str]:
    """Дополнительные термы для запроса (без повторов исходных термов)."""
    keys = {normalize(k, mode): v for k, v in PAIRS.items()}
    base = set(terms(query, mode))
    extra: list[str] = []
    for tok in raw_tokens(query):
        value = keys.get(normalize(tok, mode))
        if value:
            extra += [t for t in terms(value, mode) if t not in base and t not in extra]
    return extra
